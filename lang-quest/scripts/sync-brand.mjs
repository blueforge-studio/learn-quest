#!/usr/bin/env node
// Fan the LangQuest brand out to every group repo.
//
// Thirteen-plus regional apps (lq-nordic, lq-african, …) are each their own
// repo and their own control-plane app, but they are ONE product on
// blueforge.studio: `lang-quest`. forge-control reads `blueforge.product.yml`
// from the repo it deploys, so each group repo has to carry the file — and
// the mark it references — itself. Hand-maintaining fourteen copies is how
// they drift, so this script writes them from one source:
//
//   lang-quest/brand/logo-512.webp   the QuestLang shield-and-quill mark
//   lang-quest/brand/og.webp         the 1200x630 social card
//
// Usage (from anywhere):
//   node lang-quest/scripts/sync-brand.mjs            # every lang-quest/lq-* dir that exists
//   node lang-quest/scripts/sync-brand.mjs --dir ../lq-nordic   # one checkout, anywhere
//   node lang-quest/scripts/sync-brand.mjs --check    # exit 1 if anything would change
//
// Idempotent: identical files are left alone, so a re-run after nothing
// changed is a no-op and a re-run after a logo change touches exactly the
// files the sha-based upload will notice (blueforge docs/deploy/asset-sync.md).
import { existsSync, mkdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const langQuestRoot = dirname(dirname(fileURLToPath(import.meta.url))) // lang-quest/
const brandDir = join(langQuestRoot, 'brand')
const SOURCES = { 'brand/logo-512.webp': join(brandDir, 'logo-512.webp'), 'brand/og.webp': join(brandDir, 'og.webp') }

const SIDECAR = `# What blueforge.studio says about this app's product.
#
# GENERATED by lang-quest/scripts/sync-brand.mjs in the learn-quest repo from
# lang-quest/brand/ — edit there and re-run, do not edit here. Thirteen group
# repos deploy as thirteen control-plane apps but are one product; each carries
# this file so forge-control files its deploy under \`lang-quest\` and uploads
# the mark when its sha changes (blueforge docs/deploy/asset-sync.md).
#
# Copy (tagline, description, features) stays in blueforge's data/products.yml.
products:
  - id: lang-quest
    name: LangQuest
    apps: [web]
    primaryApp: web
    assets:
      logo: brand/logo-512.webp
      og: brand/og.webp
`

const argv = process.argv.slice(2)
const check = argv.includes('--check')
const dirIdx = argv.indexOf('--dir')
const targets = dirIdx >= 0
  ? [resolve(argv[dirIdx + 1])]
  : Object.keys(JSON.parse(readFileSync(join(langQuestRoot, 'blueforge.config.json'), 'utf-8')).apps)
      .map((appDir) => join(langQuestRoot, appDir))
      .filter((p) => existsSync(p) && statSync(p).isDirectory())

for (const [rel, src] of Object.entries(SOURCES)) {
  if (!existsSync(src)) { console.error(`missing source ${src}`); process.exit(2) }
}

let changed = 0
for (const target of targets) {
  const files = { ...Object.fromEntries(Object.entries(SOURCES).map(([rel, src]) => [rel, readFileSync(src)])), 'blueforge.product.yml': Buffer.from(SIDECAR) }
  const touched = []
  for (const [rel, want] of Object.entries(files)) {
    const dest = join(target, rel)
    const same = existsSync(dest) && readFileSync(dest).equals(want)
    if (same) continue
    touched.push(rel)
    if (!check) { mkdirSync(dirname(dest), { recursive: true }); writeFileSync(dest, want) }
  }
  changed += touched.length
  console.log(`${target}: ${touched.length ? (check ? 'would write ' : 'wrote ') + touched.join(', ') : 'up to date'}`)
}
if (targets.length === 0) { console.error('no target directories found'); process.exit(2) }
if (check && changed > 0) process.exit(1)
